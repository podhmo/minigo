// Command genbind emits the generated half of minigo's stdlib bound
// tables: one intrinsics_gen_<name>.go per spec in table.go, holding the
// pure-signature members (functions, vars, consts, plain struct typedefs)
// so the handwritten intrinsics keep only the custom adapters.
//
// Regenerate after editing the table — under the toolchain go.mod's go
// directive names, so emitted `q.<name>` references always compile:
//
//	GOTOOLCHAIN=go1.26.0 go run ./internal/cmd/genbind
package main

import (
	"context"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"

	"github.com/podhmo/minigo"
	"github.com/podhmo/minigo/index"
)

func main() {
	floor := moduleFloor()
	v := gorVersion()
	if v != floor {
		fmt.Fprintf(os.Stderr, "genbind: running under go%s but go.mod floors at go%s — rerun with GOTOOLCHAIN=go%s\n", v, floor, floor)
		os.Exit(1)
	}
	modes := map[string]minigo.PackageMode{}
	for _, sp := range specs {
		modes[sp.Path] = minigo.ModeSource
	}
	e := minigo.NewEngine(".", minigo.WithPackageModes(modes))
	ctx := context.Background()
	for _, sp := range specs {
		p, err := e.Package(ctx, sp.Path)
		if err != nil {
			fmt.Fprintf(os.Stderr, "genbind %s: %v\n", sp.Path, err)
			os.Exit(1)
		}
		if p.Index == nil {
			fmt.Fprintf(os.Stderr, "genbind %s: no source index\n", sp.Path)
			os.Exit(1)
		}
		if err := emit(sp, p.Name, p.Index); err != nil {
			fmt.Fprintf(os.Stderr, "genbind %s: %v\n", sp.Path, err)
			os.Exit(1)
		}
	}
}

// gorVersion reports the running toolchain's major.minor ("1.26").
func gorVersion() string {
	v := strings.TrimPrefix(runtime.Version(), "go")
	parts := strings.Split(v, ".")
	return strings.Join(parts[:2], ".")
}

// moduleFloor reads go.mod's go directive as a major.minor string.
func moduleFloor() string {
	b, err := os.ReadFile("go.mod")
	if err != nil {
		fmt.Fprintf(os.Stderr, "genbind: go.mod: %v\n", err)
		os.Exit(1)
	}
	for _, l := range strings.Split(string(b), "\n") {
		if f := strings.Fields(l); len(f) == 2 && f[0] == "go" {
			parts := strings.Split(f[1], ".")
			return strings.Join(parts[:2], ".")
		}
	}
	fmt.Fprintln(os.Stderr, "genbind: go.mod: no go directive")
	os.Exit(1)
	return ""
}

func emit(sp spec, pkgName string, ix *index.Index) error {
	// q is the qualifier the generated file references members through —
	// the declared package name, which differs from the last path
	// element ("net/netip" imports as netip).
	q := pkgName
	fn := camel(sp.File)
	var funcs, values, consts, structs, basics []string
	for name, d := range ix.Funcs {
		if !ast.IsExported(name) || sp.Skip[name] {
			continue
		}
		if tp := d.Func.Type.TypeParams; tp != nil && len(tp.List) > 0 {
			continue
		}
		funcs = append(funcs, name)
	}
	for name := range ix.Vars {
		if ast.IsExported(name) && !sp.Skip[name] {
			values = append(values, name)
		}
	}
	for name := range ix.Consts {
		if ast.IsExported(name) && !sp.Skip[name] {
			consts = append(consts, name)
		}
	}
	for name, ti := range ix.Types {
		if !ast.IsExported(name) || sp.Skip[name] || ti.Decl == nil {
			continue
		}
		ts, ok := ti.Decl.Spec.(*ast.TypeSpec)
		if !ok || (ts.TypeParams != nil && len(ts.TypeParams.List) > 0) {
			continue
		}
		if _, isStruct := ts.Type.(*ast.StructType); isStruct && !ts.Assign.IsValid() {
			structs = append(structs, name)
		} else {
			basics = append(basics, name)
		}
	}
	sort.Strings(funcs)
	sort.Strings(values)
	sort.Strings(consts)
	sort.Strings(structs)
	sort.Strings(basics)

	cexprs := make([]string, len(consts))
	needConst, needToken := false, false
	for i, n := range consts {
		cexprs[i] = constExpr(q, ix.Consts[n])
		needConst = needConst || strings.Contains(cexprs[i], "constant.")
		needToken = needToken || strings.Contains(cexprs[i], "token.")
	}

	var b strings.Builder
	// P2-12b: moved packages emit into internal/stdlib/<dir> with their
	// own package clause and stdlib.-qualified binding helpers.
	pkg := "minigo"
	wrap := "wrapBind"
	hostT := "hostType"
	if sp.Dir != "" {
		pkg = filepath.Base(sp.Dir)
		wrap = "stdlib.WrapBind"
		hostT = "stdlib.HostType"
	}
	fmt.Fprintf(&b, "// Code generated by internal/cmd/genbind. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//lint:file-ignore SA1019 bound tables cover deprecated stdlib members for parity.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t%q\n", pkg, sp.Path)
	if needConst {
		b.WriteString("\t\"go/constant\"\n")
	}
	if needToken {
		b.WriteString("\t\"go/token\"\n")
	}
	if sp.Dir != "" {
		b.WriteString("\n\t\"github.com/podhmo/minigo/internal/stdlib\"\n")
	}
	b.WriteString("\n\t\"github.com/podhmo/minigo/runtime\"\n)\n\n")
	fmt.Fprintf(&b, "// %sGenEntries is the generated half of %q's bound table:\n// pure-signature members; custom adapters stay handwritten.\n", fn, sp.Path)
	fmt.Fprintf(&b, "func %sGenEntries() map[string]runtime.Value {\n\treturn map[string]runtime.Value{\n", fn)
	for _, n := range funcs {
		fmt.Fprintf(&b, "\t\t%q: %s(%q, %s.%s),\n", n, wrap, q+"."+n, q, n)
	}
	for _, n := range values {
		fmt.Fprintf(&b, "\t\t%q: &runtime.GoValue{V: %s.%s},\n", n, q, n)
	}
	for i, n := range consts {
		fmt.Fprintf(&b, "\t\t%q: %s,\n", n, cexprs[i])
	}
	for _, n := range structs {
		fmt.Fprintf(&b, "\t\t%q: %s(%q, func() any { return &%s.%s{} }),\n", n, hostT, sp.Path+"."+n, q, n)
	}
	for _, n := range basics {
		fmt.Fprintf(&b, "\t\t%q: &runtime.TypeDef{Name: %q, Kind: runtime.KindNamedBasic, Pkg: &runtime.Package{Path: %q, Name: %q}},\n",
			n, sp.Path+"."+n, sp.Path, q)
	}
	b.WriteString("\t}\n}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting: %w", err)
	}
	name := "intrinsics_gen_" + sp.File + ".go"
	if sp.Dir != "" {
		name = filepath.Join(sp.Dir, "gen.go")
	}
	if err := os.WriteFile(name, src, 0o644); err != nil {
		return err
	}
	fmt.Fprintln(os.Stderr, "generated", name)
	return nil
}

// constExpr renders one bound const: untyped literals stay untyped
// (UConst, rune-tagged for char literals) so constant-domain math and
// declared-type assignment behave like source interpretation; typed or
// non-literal consts box as GoValues.
func constExpr(q string, d *index.Decl) string {
	lit, ok := constLit(d)
	if !ok {
		// an untyped non-literal (an iota heir, an alias like
		// strconv.IntSize, an arithmetic expr) stays in the constant
		// domain at int width — verified against the host build.
		if vs, ok := d.Spec.(*ast.ValueSpec); ok && vs.Type == nil {
			return fmt.Sprintf("&runtime.UConst{V: constant.MakeInt64(int64(%s.%s))}", q, d.Name)
		}
		return fmt.Sprintf("&runtime.GoValue{V: %s.%s}", q, d.Name)
	}
	switch lit.Kind {
	case token.INT:
		return fmt.Sprintf("&runtime.UConst{V: constant.MakeInt64(int64(%s.%s))}", q, d.Name)
	case token.CHAR:
		return fmt.Sprintf("&runtime.UConst{V: constant.MakeInt64(int64(%s.%s)), Rune: true}", q, d.Name)
	case token.FLOAT:
		return fmt.Sprintf("&runtime.UConst{V: constant.MakeFromLiteral(%q, token.FLOAT, 0)}", lit.Value)
	default:
		return fmt.Sprintf("&runtime.GoValue{V: %s.%s}", q, d.Name)
	}
}

// constLit finds the literal a const's value position holds, skipping
// typed specs and non-literal expressions (selectors, iota math).
func constLit(d *index.Decl) (*ast.BasicLit, bool) {
	vs, ok := d.Spec.(*ast.ValueSpec)
	if !ok || vs.Type != nil {
		return nil, false
	}
	if d.NameIdx < len(vs.Values) {
		if lit, ok := vs.Values[d.NameIdx].(*ast.BasicLit); ok {
			return lit, true
		}
	}
	for _, v := range d.Inherited {
		if lit, ok := v.(*ast.BasicLit); ok {
			return lit, true
		}
	}
	return nil, false
}

// camel turns a file suffix like "encoding_hex" into the exported-name
// stem "encodingHex" used for the GenEntries function.
func camel(s string) string {
	var b strings.Builder
	up := false
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up {
			b.WriteString(strings.ToUpper(string(r)))
			up = false
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

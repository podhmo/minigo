package main

import (
	"fmt"
	"sort"
	"strings"
)

// method is one optional surface a proxy variant can carry: suffix
// joins the variant name, sig the forwarded method, call the
// expression it delegates to (receivers are named s).
type method struct {
	suffix string
	sig    string // e.g. `WriteTo(w io.Writer) (int64, error)`
	call   string // e.g. `s.writeTo(w)` or `s.inner.Seek(offset, whence)`
}

var (
	writeTo  = method{"WT", "WriteTo(w io.Writer) (int64, error)", "s.writeTo(w)"}
	readFrom = method{"RF", "ReadFrom(r io.Reader) (int64, error)", "s.readFrom(r)"}
	seek     = method{"Seek", "Seek(offset int64, whence int) (int64, error)", "s.inner.Seek(offset, whence)"}
	readDir  = method{"RD", "ReadDir(name string) ([]fs.DirEntry, error)", "s.readDir(name)"}
	readFile = method{"RF", "ReadFile(name string) ([]byte, error)", "s.readFile(name)"}
)

// innerMethod swaps the target onto the inner *scriptIface — the
// file-level variants forward to s.inner instead of s.
func inner(m method, expr string) method {
	m.call = expr
	return m
}

// family: the embed base and its optional methods, in suffix order.
var families = []struct {
	base    string
	methods []method
}{
	{"*scriptIface", []method{writeTo, readFrom}},
	{"*scriptFS", []method{readDir, readFile}},
	{"*scriptFile", []method{seek, inner(writeTo, "s.inner.writeTo(w)")}},
	{"scriptDirFile", []method{inner(seek, "s.inner.Seek(offset, whence)"), inner(writeTo, "s.inner.writeTo(w)")}},
}

func emit(b *strings.Builder) {
	b.WriteString(`// Code generated by internal/cmd/genifaces. DO NOT EDIT.

package vm

import (
	"io"
	"io/fs"
)

`)
	for _, f := range families {
		// every non-empty subset of the family's optional methods,
		// smallest first (WT, RF, WTRF order for readability).
		var combos [][]method
		for mask := 1; mask < 1<<len(f.methods); mask++ {
			var combo []method
			for i, m := range f.methods {
				if mask&(1<<i) != 0 {
					combo = append(combo, m)
				}
			}
			combos = append(combos, combo)
		}
		sort.SliceStable(combos, func(i, j int) bool { return len(combos[i]) < len(combos[j]) })

		// type block first, then the forwarded methods.
		b.WriteString("type (\n")
		for _, c := range combos {
			fmt.Fprintf(b, "\t%s%s struct{ %s }\n", strings.TrimPrefix(f.base, "*"), suffixes(c), f.base)
		}
		b.WriteString(")\n\n")
		for _, c := range combos {
			name := strings.TrimPrefix(f.base, "*") + suffixes(c)
			for _, m := range c {
				fmt.Fprintf(b, "func (s %s) %s { return %s }\n\n", name, m.sig, m.call)
			}
		}
	}
}

func suffixes(ms []method) string {
	var b strings.Builder
	for _, m := range ms {
		b.WriteString(m.suffix)
	}
	return b.String()
}
